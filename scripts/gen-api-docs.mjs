// Generates "obsidian/ROBLOX UI STUDIO/API_REFERENCE.md" from the tool registry,
// so the reference can never drift from the implementation. Run: npm run docs:api
import { build } from "esbuild";
import { writeFileSync, mkdirSync, rmSync } from "node:fs";
import path from "node:path";

const out = path.resolve(".test-dist/gen-api.mjs");
await build({
  stdin: {
    contents: `import { TOOLS } from "./src/server/tools"; import { z } from "zod"; export { TOOLS, z };`,
    resolveDir: process.cwd(), loader: "ts",
  },
  bundle: true, platform: "node", format: "esm", outfile: out, packages: "external", logLevel: "error",
});
const { TOOLS, z } = await import(out);
rmSync(out);

const typeOf = (s) => {
  if (!s) return "any";
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(" | ");
  if (s.type === "array") return `${typeOf(s.items)}[]`;
  if (s.type === "object" && s.properties) return "object";
  if (s.type === "object") return "record";
  return s.type ?? "any";
};

let md = `# API Reference (tools)\n\n> Generated by \`npm run docs:api\` from \`src/server/tools.ts\`. Do not edit by hand.\n\n`;
md += `The same ${TOOLS.length} tools are available over **MCP** (\`dist/mcp.mjs\`, stdio) and **HTTP** (\`POST /api/tools/<name>\` with a JSON body). Every result is \`{ ok: true, ... }\` or \`{ ok: false, error, hint? }\`.\n\n`;
md += `| Tool | Read-only | Summary |\n|---|---|---|\n`;
for (const t of TOOLS) md += `| [\`${t.name}\`](#${t.name}) | ${t.readOnly ? "yes" : ""} | ${t.title} |\n`;
for (const t of TOOLS) {
  const schema = z.toJSONSchema(z.object(t.input), { unrepresentable: "any" });
  md += `\n## ${t.name}\n\n${t.description}\n\n`;
  const props = Object.entries(schema.properties ?? {});
  if (!props.length) { md += `_No parameters._\n`; continue; }
  md += `| Parameter | Type | Required | Description |\n|---|---|---|---|\n`;
  for (const [k, s] of props) md += `| \`${k}\` | ${typeOf(s).replace(/\|/g, "\\|")} | ${(schema.required ?? []).includes(k) ? "yes" : ""} | ${(s.description ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ")} |\n`;
}
const dir = path.resolve("obsidian/ROBLOX UI STUDIO");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "API_REFERENCE.md"), md);
console.log(`wrote API_REFERENCE.md (${TOOLS.length} tools)`);
